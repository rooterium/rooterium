"""Generate the web assets from the originals in design/ (CLAUDE.md:
web assets are generated by a script, never edited by hand).

Run from the repository root after changing an original or the fonts:

    uv run python design/build_web_assets.py

Writes to core/static/core/img/:
- favicon.ico (16, 32, 48 px), favicon-32.png, apple-touch-icon.png
  (180 px), icon-512.png: interim mark (gold "R" in Cormorant Garamond with
  a thin gold ring) until a real logo exists.
- og-default.jpg (1200 × 630): default Open Graph image, the region map
  mood image (atmosphere only) darkened, with the site name and tagline.
"""

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
DESIGN = ROOT / "design"
FONTS = ROOT / "core/static/core/fonts"
OUT = ROOT / "core/static/core/img"

# Palette V2 (docs/PROJECT_BRIEF.md, section 6)
BG = "#0b0a09"
TEXT = "#eee3d1"
TEXT_SECONDARY = "#c9bfae"
ACCENT_2 = "#d98a3f"
GOLD = "#c8a15d"

HEADING_FONT = FONTS / "cormorant-garamond-latin-600-normal.woff2"
BODY_FONT = FONTS / "manrope-latin-wght-normal.woff2"


def body_font(size: int, weight: int) -> ImageFont.FreeTypeFont:
    font = ImageFont.truetype(BODY_FONT, size)
    font.set_variation_by_axes([weight])
    return font


def mark(size: int) -> Image.Image:
    """Square icon: gold "R" in a thin gold ring on the page background."""
    scale = 4  # draw large, then downsample for smooth edges
    s = size * scale
    image = Image.new("RGB", (s, s), BG)
    draw = ImageDraw.Draw(image)
    inset = s * 0.08
    draw.ellipse(
        (inset, inset, s - inset, s - inset), outline=GOLD, width=max(scale, s // 40)
    )
    font = ImageFont.truetype(HEADING_FONT, int(s * 0.62))
    draw.text((s / 2, s / 2), "R", font=font, fill=GOLD, anchor="mm")
    return image.resize((size, size), Image.Resampling.LANCZOS)


def og_image() -> Image.Image:
    width, height = 1200, 630
    source = Image.open(DESIGN / "rooterium_v2_region_map.png").convert("RGB")
    # Crop the centre to the target aspect ratio, then scale down.
    target_ratio = width / height
    sw, sh = source.size
    crop_w = min(sw, int(sh * target_ratio))
    crop_h = int(crop_w / target_ratio)
    left, top = (sw - crop_w) // 2, (sh - crop_h) // 2
    image = source.crop((left, top, left + crop_w, top + crop_h)).resize(
        (width, height), Image.Resampling.LANCZOS
    )

    # Darken: a gradient from almost opaque on the left (text side) to 45 %.
    overlay = Image.new("RGBA", (width, height))
    draw = ImageDraw.Draw(overlay)
    for x in range(width):
        alpha = int(255 * (0.92 - 0.47 * x / width))
        draw.line([(x, 0), (x, height)], fill=(11, 10, 9, alpha))
    image = Image.alpha_composite(image.convert("RGBA"), overlay).convert("RGB")

    draw = ImageDraw.Draw(image)
    x = 80
    draw.text(
        (x, 200),
        "ARMENIAN HISTORY, TRADITIONS, MYTHS, SYMBOLS AND MUSIC",
        font=body_font(22, 600),
        fill=ACCENT_2,
    )
    draw.text(
        (x, 250), "Rooterium", font=ImageFont.truetype(HEADING_FONT, 120), fill=TEXT
    )
    draw.text(
        (x, 400),
        "Find your way back to your roots.",
        font=body_font(38, 500),
        fill=TEXT_SECONDARY,
    )
    draw.line([(x, 470), (x + 120, 470)], fill=GOLD, width=2)
    return image


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    big = mark(512)
    big.save(OUT / "icon-512.png", optimize=True)
    mark(180).save(OUT / "apple-touch-icon.png", optimize=True)
    mark(32).save(OUT / "favicon-32.png", optimize=True)
    mark(48).save(OUT / "favicon.ico", sizes=[(16, 16), (32, 32), (48, 48)])
    og_image().save(OUT / "og-default.jpg", quality=85, optimize=True, progressive=True)
    for path in sorted(OUT.iterdir()):
        print(f"{path.relative_to(ROOT)}  {path.stat().st_size // 1024} KB")


if __name__ == "__main__":
    main()
