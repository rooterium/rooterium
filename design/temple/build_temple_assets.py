"""Fetch the temple originals and build their web versions
(docs/TEMPLE_BRIEF.md, section 4; CLAUDE.md: web assets are generated by a
script, never edited by hand).

Run from the repository root:

    uv run python design/temple/build_temple_assets.py fetch
    uv run python design/temple/build_temple_assets.py build

fetch   Download every original listed in manifest.json that is missing
        from design/temple/originals/ and check its size and SHA-256
        against the manifest. ``--record`` writes size and hash into the
        manifest instead (only when an asset is added).
build   Write the web versions into design/temple/web/ (git-ignored):
        - images: <key>-1920.webp and <key>-960.webp (never upscaled);
        - videos: <key>.mp4 (H.264, 1280×720, no audio, faststart),
          <key>-poster.webp (first frame) and <key>-last.webp (last frame,
          held as a still after the video ends);
        and the film-grain texture core/static/core/img/grain.png
        (generated noise, committed like the favicons).

Needs ffmpeg and ffprobe on PATH (Homebrew: ``brew install ffmpeg``).
"""

import argparse
import hashlib
import json
import random
import shutil
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path

from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parents[2]
TEMPLE = ROOT / "design/temple"
MANIFEST = TEMPLE / "manifest.json"
ORIGINALS = TEMPLE / "originals"
WEB = TEMPLE / "web"
GRAIN = ROOT / "core/static/core/img/grain.png"

IMAGE_WIDTHS = (1920, 960)
WEBP_QUALITY = 80
VIDEO_CRF = 22  # with -tune grain; CRF 26 visibly smoothed the film grain
VIDEO_TARGET_BYTES = 3_000_000  # brief: under 3 MB per clip
GRAIN_SIZE = 256


def load_manifest() -> dict:
    return json.loads(MANIFEST.read_text())


def original_path(asset: dict) -> Path:
    suffix = ".mp4" if asset["kind"] == "video" else ".png"
    return ORIGINALS / f"{asset['key']}{suffix}"


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as file:
        for chunk in iter(lambda: file.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def download(url: str, target: Path) -> None:
    request = urllib.request.Request(url, headers={"User-Agent": "asset-fetch/1.0"})
    partial = target.with_suffix(target.suffix + ".part")
    with (
        urllib.request.urlopen(request, timeout=60) as response,
        partial.open("wb") as file,
    ):
        shutil.copyfileobj(response, file)
    partial.rename(target)


def fetch(record: bool) -> int:
    manifest = load_manifest()
    ORIGINALS.mkdir(parents=True, exist_ok=True)
    errors = 0
    for asset in manifest["assets"]:
        path = original_path(asset)
        if not path.exists():
            print(f"download {asset['key']}")
            download(asset["source"], path)
        size, digest = path.stat().st_size, sha256(path)
        if record:
            asset["bytes"], asset["sha256"] = size, digest
        elif (size, digest) != (asset.get("bytes"), asset.get("sha256")):
            print(f"MISMATCH {asset['key']}: {size} bytes, {digest}", file=sys.stderr)
            errors += 1
            continue
        print(f"ok {asset['key']} {size / 1e6:.1f} MB")
    if record:
        MANIFEST.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n")
        print(f"recorded sizes and hashes in {MANIFEST.relative_to(ROOT)}")
    return 1 if errors else 0


def save_webp(image: Image.Image, target: Path, width: int) -> None:
    if image.width > width:
        height = round(image.height * width / image.width)
        image = image.resize((width, height), Image.Resampling.LANCZOS)
    image.save(target, "WEBP", quality=WEBP_QUALITY, method=6)


def build_image(asset: dict) -> None:
    image = Image.open(original_path(asset)).convert("RGB")
    for width in IMAGE_WIDTHS:
        save_webp(image, WEB / f"{asset['key']}-{width}.webp", width)


def ffmpeg(*args: str) -> None:
    subprocess.run(
        ["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", *args], check=True
    )


def build_video(asset: dict) -> None:
    source = original_path(asset)
    target = WEB / f"{asset['key']}.mp4"
    ffmpeg(
        "-i", str(source),
        "-an",
        "-vf", "scale=1280:720:force_original_aspect_ratio=increase,crop=1280:720",
        "-c:v", "libx264", "-preset", "slow", "-tune", "grain", "-crf", str(VIDEO_CRF),
        "-profile:v", "high", "-pix_fmt", "yuv420p",
        "-movflags", "+faststart",
        str(target),
    )  # fmt: skip
    if target.stat().st_size > VIDEO_TARGET_BYTES:
        print(f"  note: {target.name} is over the 3 MB target", file=sys.stderr)
    # Stills from the web version, so they match the video frame for frame.
    with tempfile.TemporaryDirectory() as tmp:
        first, last = Path(tmp, "first.png"), Path(tmp, "last.png")
        ffmpeg("-i", str(target), "-frames:v", "1", str(first))
        ffmpeg("-sseof", "-0.5", "-i", str(target), "-update", "1", str(last))
        save_webp(Image.open(first), WEB / f"{asset['key']}-poster.webp", 1280)
        save_webp(Image.open(last), WEB / f"{asset['key']}-last.webp", 1280)


def build_grain() -> None:
    """A seamless tile of soft monochrome noise around mid-grey.

    Generated with a fixed seed so rebuilding gives the same file. The tile is
    blurred as a 3×3 mosaic and the centre cut out, so it tiles without seams.
    """
    rng = random.Random(1969)
    tile = Image.new("L", (GRAIN_SIZE, GRAIN_SIZE))
    tile.putdata(
        [max(0, min(255, round(rng.gauss(128, 48)))) for _ in range(GRAIN_SIZE**2)]
    )
    mosaic = Image.new("L", (GRAIN_SIZE * 3, GRAIN_SIZE * 3))
    for x in range(3):
        for y in range(3):
            mosaic.paste(tile, (x * GRAIN_SIZE, y * GRAIN_SIZE))
    mosaic = mosaic.filter(ImageFilter.GaussianBlur(0.6))
    box = (GRAIN_SIZE, GRAIN_SIZE, GRAIN_SIZE * 2, GRAIN_SIZE * 2)
    mosaic.crop(box).save(GRAIN, "PNG", optimize=True)


def build() -> int:
    if not shutil.which("ffmpeg"):
        print("ffmpeg not found on PATH", file=sys.stderr)
        return 1
    manifest = load_manifest()
    missing = [a["key"] for a in manifest["assets"] if not original_path(a).exists()]
    if missing:
        print(
            f"missing originals (run fetch first): {', '.join(missing)}",
            file=sys.stderr,
        )
        return 1
    WEB.mkdir(parents=True, exist_ok=True)
    for asset in manifest["assets"]:
        print(f"build {asset['key']}")
        (build_video if asset["kind"] == "video" else build_image)(asset)
    build_grain()
    for path in sorted(WEB.iterdir()):
        print(f"  {path.name:32} {path.stat().st_size / 1e6:6.2f} MB")
    print(f"  {GRAIN.name:32} {GRAIN.stat().st_size / 1e6:6.2f} MB (static)")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    commands = parser.add_subparsers(dest="command", required=True)
    fetch_parser = commands.add_parser("fetch", help="download and check originals")
    fetch_parser.add_argument(
        "--record", action="store_true", help="write sizes and hashes to the manifest"
    )
    commands.add_parser("build", help="build the web versions and the grain")
    args = parser.parse_args()
    if args.command == "fetch":
        return fetch(args.record)
    return build()


if __name__ == "__main__":
    sys.exit(main())
